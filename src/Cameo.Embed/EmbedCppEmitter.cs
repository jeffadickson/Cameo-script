using System.Globalization;
using System.Text;

namespace Cameo.Embed;

/// <summary>
/// Emits a zero-constructor, freestanding C++20 header embedding a compiled <c>CEMB</c>
/// image directly into <c>.rodata</c> alongside static pool capacity constants, flags, and host IDs.
/// </summary>
public static class EmbedCppEmitter
{
    /// <summary>Formats a compiled CEMB image as a self-contained C++20 header.</summary>
    public static string EmitHeader(EmbedCompiledImage image, string symbolPrefix = "kCameoProgram", string cppNamespace = "cameo::programs")
    {
        ArgumentNullException.ThrowIfNull(image);
        string prefix = SanitizeIdentifier(string.IsNullOrWhiteSpace(symbolPrefix) ? "kCameoProgram" : symbolPrefix);
        string ns = string.IsNullOrWhiteSpace(cppNamespace) ? "cameo::programs" : cppNamespace.Trim();
        EmbedProgramReport r = image.Report;

        var sb = new StringBuilder(image.Bytes.Length * 6 + 1024);
        sb.AppendLine("#pragma once");
        sb.AppendLine("// Auto-generated by Cameo.Embed — do not edit manually.");
        sb.Append("// Source: ").AppendLine(image.SourceName.Replace('\r', ' ').Replace('\n', ' '));
        sb.Append("// Size: ").Append(r.ImageBytes.ToString(CultureInfo.InvariantCulture))
          .Append(" bytes | CRC-32C: 0x").Append(r.Crc32C.ToString("X8", CultureInfo.InvariantCulture))
          .Append(" | Flags: 0x").Append(((ushort)r.Flags).ToString("X4", CultureInfo.InvariantCulture))
          .Append(" | Protos: ").Append(r.ProtoCount.ToString(CultureInfo.InvariantCulture))
          .Append(" | Instructions: ").AppendLine(r.InstructionCount.ToString(CultureInfo.InvariantCulture));
        sb.AppendLine("#include <stddef.h>");
        sb.AppendLine("#include <stdint.h>");
        sb.AppendLine();
        sb.Append("namespace ").Append(ns).AppendLine(" {");
        sb.AppendLine();
        sb.Append("struct ").Append(prefix).AppendLine("_requirements {");
        sb.Append("    static constexpr size_t stack_slots = ").Append(Math.Max(32, r.RequiredStackSlots).ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr size_t frames = ").Append(Math.Max(4, r.RequiredFrames).ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr size_t globals = ").Append(Math.Max(1, r.GlobalCount).ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr size_t boxes = ").Append(Math.Max(1, r.RequiredBoxes).ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr size_t closures = ").Append(Math.Max(1, r.RequiredClosures).ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr size_t records = ").Append(Math.Max(1, r.RequiredRecords).ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr size_t record_slots = ").Append(Math.Max(4, r.RequiredRecordSlots).ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr uint16_t flags = 0x").Append(((ushort)r.Flags).ToString("X4", CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr bool uses_float = ").Append(r.Flags.HasFlag(EmbedImageFlags.HasFloat) ? "true" : "false").AppendLine(";");
        sb.Append("    static constexpr bool uses_mem_write = ").Append(r.Flags.HasFlag(EmbedImageFlags.HasMemWrite) ? "true" : "false").AppendLine(";");
        sb.Append("    static constexpr uint32_t crc32c = 0x").Append(r.Crc32C.ToString("X8", CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.Append("    static constexpr size_t image_bytes = ").Append(r.ImageBytes.ToString(CultureInfo.InvariantCulture)).AppendLine("u;");
        sb.AppendLine("};");
        sb.AppendLine();

        if (r.HostImports.Count > 0)
        {
            sb.Append("namespace ").Append(prefix).AppendLine("_hosts {");
            foreach (EmbedHostImport host in r.HostImports)
            {
                sb.Append("    inline constexpr uint16_t ")
                  .Append(SanitizeIdentifier(host.Name))
                  .Append(" = ")
                  .Append(host.HostId.ToString(CultureInfo.InvariantCulture))
                  .AppendLine("u;");
            }
            sb.AppendLine("}");
            sb.AppendLine();
        }

        sb.Append("alignas(8) inline constexpr uint8_t ").Append(prefix)
          .Append('[').Append(image.Bytes.Length.ToString(CultureInfo.InvariantCulture)).AppendLine("] = {");

        for (int i = 0; i < image.Bytes.Length; i += 16)
        {
            sb.Append("    ");
            int end = Math.Min(i + 16, image.Bytes.Length);
            for (int j = i; j < end; j++)
            {
                sb.Append("0x").Append(image.Bytes[j].ToString("X2", CultureInfo.InvariantCulture));
                if (j + 1 < image.Bytes.Length)
                    sb.Append(j + 1 < end ? ", " : ",");
            }
            sb.AppendLine();
        }

        sb.AppendLine("};");
        sb.AppendLine();
        sb.Append("} // namespace ").AppendLine(ns);
        return sb.ToString();
    }

    private static string SanitizeIdentifier(string name)
    {
        var sb = new StringBuilder(name.Length + 1);
        for (int i = 0; i < name.Length; i++)
        {
            char c = name[i];
            if (char.IsAsciiLetterOrDigit(c) || c == '_') sb.Append(c);
            else sb.Append('_');
        }
        if (sb.Length == 0 || char.IsAsciiDigit(sb[0]))
            sb.Insert(0, '_');
        return sb.ToString();
    }
}
